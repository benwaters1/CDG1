"""Fresh values for the secrets this app makes up itself, written to a file.

    python tools/new_keys.py                      every one of them
    python tools/new_keys.py FLASK_SECRET_KEY     just the ones named

For rotating keys after they may have been seen -- see "Rotating the keys"
in DEPLOY.md for the order and for what each change signs out or breaks.

The values go into `.env.new-keys` beside app.py, never onto the screen: a
secret printed to a terminal ends up in scrollback, in a pasted log, in a
chat. `.env.*` is gitignored, and the app reads only `.env`, so the file is
inert until somebody copies a line out of it into Railway. Delete it once
they have.

It refuses to overwrite an existing file. Half the values from a first run
may already be in Railway, and replacing them with a second set would leave
nobody knowing which is live.

Keys that belong to a provider -- Stripe, Resend, Pennylane, Anthropic,
Microsoft -- are not here. Those are issued by the provider, on its own
dashboard, and revoked there.
"""
import os
import secrets
import sys

from cryptography.fernet import Fernet

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(HERE, ".env.new-keys")

# name -> (how to make one, what changing it does)
KEYS = {
    "FLASK_SECRET_KEY": (
        lambda: secrets.token_hex(32),
        "signs everyone out (staff, owner, the till, guests' accounts); a form "
        "open at that moment fails once"),
    "VAULT_ENCRYPTION_KEY": (
        lambda: Fernet.generate_key().decode(),
        "FIRST copy the current value into VAULT_ENCRYPTION_KEY_PREVIOUS, or "
        "every Vault password and bank detail becomes unreadable"),
    "GUDANES_INGEST_KEY": (
        lambda: secrets.token_urlsafe(32),
        "update receipts.ini on the chateau PC and the camera-roll uploader"),
    "ICAL_SYNC_TOKEN": (
        lambda: secrets.token_urlsafe(32),
        "only if set: update the scheduler that calls /api/sync-ical"),
    "DIGEST_TOKEN": (
        lambda: secrets.token_urlsafe(32),
        "only if set: update the scheduler that calls /api/owner-digest"),
    "GUEST_LOOKUP_TOKEN": (
        lambda: secrets.token_urlsafe(32),
        "only if set: enter it again in the Outlook add-in"),
    "OFFICE_DISPLAY_TOKEN": (
        lambda: secrets.token_urlsafe(32),
        "only if set: change the wallboard's address to the new token"),
}


def main(argv):
    wanted = argv[1:] or list(KEYS)
    unknown = [n for n in wanted if n not in KEYS]
    if unknown:
        print(f"Not a key this makes: {', '.join(unknown)}")
        print(f"It makes: {', '.join(KEYS)}")
        return 2
    if os.path.exists(OUT):
        print(f"{OUT} already exists, so nothing was written.")
        print("If its values are pasted already, delete it and run this again.")
        return 1
    lines = ["# Generated by tools/new_keys.py. Paste each into Railway -> Variables,",
             "# then DELETE THIS FILE. The app never reads it.", ""]
    for name in wanted:
        make, note = KEYS[name]
        lines += [f"# {note}", f"{name}={make()}", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    try:
        os.chmod(OUT, 0o600)
    except OSError:
        pass
    print(f"Wrote {len(wanted)} new value(s) to {OUT}:")
    for name in wanted:
        print(f"  {name}")
    print("The values are in the file only. Delete it once they are in Railway.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
